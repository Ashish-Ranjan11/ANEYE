% ============================================================
% HELPER: FIND LEGACY SIMEVENTS BLOCK
% ============================================================

function blockPath = findLegacyBlock( ...
    rootLibrary, ...
    targetName)

blocks = find_system( ...
    rootLibrary, ...
    'LookUnderMasks', ...
    'all', ...
    'FollowLinks', ...
    'on', ...
    'Type', ...
    'Block');

blockPath = '';

for k = 1:length(blocks)

    cleanName = strrep( ...
        blocks{k}, ...
        sprintf('\n'), ...
        ' ');

    if ~isempty( ...
            strfind( ...
                cleanName, ...
                targetName))

        blockPath = blocks{k};

        break;

    end

end

if isempty(blockPath)

    error( ...
        ['Legacy SimEvents block not found: ' ...
         targetName]);

end

end



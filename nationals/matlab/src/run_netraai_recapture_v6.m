function result = run_netraai_recapture_v6()
% RUN_NETRAAI_RECAPTURE_V6
%
% ANEYE / NetraAI Digital Twin V6
% ONE-PASS RECAPTURE RESOURCE LOOP
%
% MATLAB / SimEvents R2014a compatible.
%
% BASE MODEL
% ----------
% NetraAI_DigitalTwin_V5_ParallelCapture
%
% KEY V6 CHANGE
% -------------
% Primary and recapture traffic are merged using:
%
%       simeventslib/Routing/Path Combiner
%
% NOT Input Switch.
%
% This avoids the R2014a Round-Robin Input Switch deadlock where
% the switch can wait for an empty feedback input.
%
%
% PRIMARY FLOW
% ------------
%
% Population Merger
%        |
% Set flowType = 1
%        |
%        +-----------------------------+
%                                      |
%                               Path Combiner
%                                      |
%                            Capture Load Balancer
%                               /             \
%                        Capture 1         Capture 2
%                               \             /
%                                Capture Merger
%                                      |
%                                  AI Queue
%                                      |
%                                   TRACE AI
%                                      |
%                              Post-AI Flow Router
%                               /              \
%                     flowType=1              flowType=2
%                         |                       |
%                    TRACE Router          RECAPTURE COMPLETE
%
%
% RECAPTURE FLOW
% --------------
%
% TRACE Route 5
%       |
% Recapture Preparation
%       |
% Set flowType = 2
%       |
% Path Combiner
%       |
% second Capture
%       |
% second AI pass
%       |
% RECAPTURE COMPLETE
%
%
% IMPORTANT
% ---------
% A recapture is allowed ONE additional acquisition/AI pass.
% It does NOT enter TRACE routing for a second time.
%
% Therefore routeCode=5 cannot create an infinite loop.
%
% Post-recapture clinical outcome is NOT inferred because that
% behavior has not yet been measured.
%
%
% PROVENANCE
% ----------
% REQUIREMENT
%   Annual target = 100,000 primary screenings
%
% MEASURED
%   AI service time = 8.67151 s
%   based on one frozen reference case only
%
% ASSUMPTION
%   300 operating days/year
%   8 operating hours/day
%   Capture service = 120 s
%   Recapture preparation = 20 s
%   Ophthalmology review = 30 s
%   Human review = 45 s
%
% ENGINEERING TEST
%   TRACE route mix = 20% each
%
% SIMULATED
%   Queue waits
%   Resource utilization
%   Recapture workload
%   Throughput
%
% This is an engineering digital twin.
% It is NOT clinical validation.

clc

fprintf('\n');
fprintf('========================================================\n');
fprintf(' ANEYE / NETRAAI DIGITAL TWIN V6\n');
fprintf(' PATH-COMBINER ONE-PASS RECAPTURE LOOP\n');
fprintf('========================================================\n');

% ============================================================
% 1. PATHS
% ============================================================

projectRoot = pwd;

srcDir = fullfile( ...
    projectRoot, ...
    'nationals', ...
    'matlab', ...
    'src');

modelDir = fullfile( ...
    projectRoot, ...
    'nationals', ...
    'simulink');

resultsDir = fullfile( ...
    modelDir, ...
    'results');

addpath(srcDir);

if ~exist(resultsDir,'dir')
    mkdir(resultsDir);
end

baseModel = ...
    'NetraAI_DigitalTwin_V5_ParallelCapture';

mdl = ...
    'NetraAI_DigitalTwin_V6_RecaptureLoop';

baseModelFile = fullfile( ...
    modelDir, ...
    [baseModel '.mdl']);

modelFile = fullfile( ...
    modelDir, ...
    [mdl '.mdl']);

if exist(baseModelFile,'file') ~= 2

    error( ...
        ['V5 baseline model not found: ' ...
         baseModelFile]);

end

fprintf('\nValidated V5 baseline:\n%s\n', ...
    baseModelFile);

% ============================================================
% 2. DISTRICT SCENARIO
% ============================================================

annualTarget = 100000;

workingDays = 300;
hoursPerDay = 8;

simulationHours = 8;

simulationTime = ...
    simulationHours * 3600;

operatingSecondsYear = ...
    workingDays ...
    * hoursPerDay ...
    * 3600;

arrivalPeriod = ...
    operatingSecondsYear ...
    / annualTarget;

requiredPerHour = ...
    annualTarget ...
    / (workingDays * hoursPerDay);

captureTime = 120.0;
% ASSUMPTION

aiTime = 8.67151;
% MEASURED ON ONE REFERENCE CASE

ophthalmologyTime = 30.0;
% ASSUMPTION

humanReviewTime = 45.0;
% ASSUMPTION

recapturePreparationTime = 20.0;
% ASSUMPTION

% ============================================================
% 3. PRINT CONTRACT
% ============================================================

fprintf('\n--- V6 SCENARIO CONTRACT ---\n');

fprintf( ...
    'Annual requirement        : %.0f/year\n', ...
    annualTarget);

fprintf( ...
    'Required primary rate     : %.2f cases/hour\n', ...
    requiredPerHour);

fprintf( ...
    'Primary arrival period    : %.3f s\n', ...
    arrivalPeriod);

fprintf( ...
    'Capture stations          : 2\n');

fprintf( ...
    'Capture service           : %.2f s [ASSUMPTION]\n', ...
    captureTime);

fprintf( ...
    'AI service                : %.5f s [MEASURED-1 CASE]\n', ...
    aiTime);

fprintf( ...
    'Recapture preparation     : %.2f s [ASSUMPTION]\n', ...
    recapturePreparationTime);

fprintf( ...
    'TRACE route mix           : 20%% each [ENGINEERING TEST]\n');

fprintf( ...
    'Feedback merge            : PATH COMBINER\n');

fprintf( ...
    'Recapture policy          : ONE PASS ONLY\n');

fprintf( ...
    'Simulation horizon        : %.0f h\n', ...
    simulationHours);

% ============================================================
% 4. REMOVE OLD V6
% ============================================================

try
    close_system(mdl,0);
catch
end

if exist(modelFile,'file') == 2
    delete(modelFile);
end

% ============================================================
% 5. CLONE VALIDATED V5
% ============================================================

fprintf('\nLoading V5 baseline...\n');

load_system(baseModelFile);

save_system( ...
    baseModel, ...
    modelFile);

try
    close_system(baseModel,0);
catch
end

load_system(modelFile);

fprintf('Fresh V6 cloned from validated V5.\n');

% ============================================================
% 6. LOAD LIBRARIES
% ============================================================

load_system('simeventslib');

pathCombinerLib = ...
    'simeventslib/Routing/Path Combiner';

outputSwitchLib = ...
    'simeventslib/Routing/Output Switch';

serverLib = ...
    'simeventslib/Servers/Single Server';

setAttributeLib = ...
    'simeventslib/Attributes/Set Attribute';

sinkLib = findLegacyBlock( ...
    'simeventslib', ...
    'Entity Sink');

% ============================================================
% 7. V5 BLOCK PATHS
% ============================================================

populationMerger = ...
    [mdl '/Population Merger'];

captureLoadBalancer = ...
    [mdl '/Capture Load Balancer'];

captureQueue1 = ...
    [mdl '/Capture Queue'];

captureQueue2 = ...
    [mdl '/Capture Queue 2'];

captureServer1 = ...
    [mdl '/Fundus Capture'];

captureServer2 = ...
    [mdl '/Fundus Capture 2'];

captureMerger = ...
    [mdl '/Capture Merger'];

aiQueue = ...
    [mdl '/AI Queue'];

aiServer = ...
    [mdl '/TRACE AI Processing'];

traceRouter = ...
    [mdl '/TRACE Router'];

ophServer = ...
    [mdl '/Ophthalmologist Review'];

humanServer = ...
    [mdl '/Human Reviewer'];

oldRecaptureSink = ...
    [mdl '/5 RECAPTURE'];

oldRoute5Logger = ...
    [mdl '/Route 5 Count'];

% ============================================================
% 8. VERIFY V5 STRUCTURE
% ============================================================

requiredBlocks = { ...
    populationMerger, ...
    captureLoadBalancer, ...
    captureQueue1, ...
    captureQueue2, ...
    captureServer1, ...
    captureServer2, ...
    captureMerger, ...
    aiQueue, ...
    aiServer, ...
    traceRouter};

for k = 1:length(requiredBlocks)

    try

        get_param( ...
            requiredBlocks{k}, ...
            'Handle');

    catch

        error( ...
            ['Required V5 block missing: ' ...
             requiredBlocks{k}]);

    end

end

fprintf('V5 structural verification: PASS\n');

% ============================================================
% 9. REMOVE OLD TERMINAL RECAPTURE PATH
% ============================================================

fprintf('\nRemoving V5 terminal recapture path...\n');

try
    delete_block(oldRoute5Logger);
catch
end

try
    delete_block(oldRecaptureSink);
catch
end

fprintf('V5 Route-5 sink removed.\n');

% ============================================================
% 10. CREATE PRIMARY FLOW ATTRIBUTE
% ============================================================
%
% flowType = 1 : primary
% flowType = 2 : recapture

primaryFlowSetter = ...
    [mdl '/Set Primary Flow'];

try
    delete_block(primaryFlowSetter);
catch
end

add_block( ...
    setAttributeLib, ...
    primaryFlowSetter, ...
    'Position', ...
    [555 385 700 435]);

set_param( ...
    primaryFlowSetter, ...
    'AttributeName', ...
    'flowType');

set_param( ...
    primaryFlowSetter, ...
    'AttributeFrom', ...
    'Dialog');

set_param( ...
    primaryFlowSetter, ...
    'AttributeValue', ...
    '1');

set_param( ...
    primaryFlowSetter, ...
    'AttributeCreate', ...
    'on');

% ============================================================
% 11. CREATE PATH COMBINER
% ============================================================
%
% This is the critical R2014a fix.
%
% IN1 = primary cases
% IN2 = recapture feedback
%
% Unlike Input Switch, Path Combiner does not need to select
% an empty input before allowing the other input to pass.

acquisitionCombiner = ...
    [mdl '/Acquisition Path Combiner'];

try
    delete_block(acquisitionCombiner);
catch
end

add_block( ...
    pathCombinerLib, ...
    acquisitionCombiner, ...
    'Position', ...
    [750 370 890 475]);

set_param( ...
    acquisitionCombiner, ...
    'NumberInputPorts', ...
    '2');

% Prefer new primary input only when arrivals occur at the
% exact same simulation event time.
%
% This does NOT create the Round-Robin deadlock.

set_param( ...
    acquisitionCombiner, ...
    'InputPortPrecedence', ...
    'IN1 port');

set_param( ...
    acquisitionCombiner, ...
    'SpecifyEventPriority', ...
    'off');

fprintf('Acquisition Path Combiner created.\n');

% ============================================================
% 12. CREATE PRIMARY ENTRY PATH
% ============================================================

forceEntityConnection( ...
    mdl, ...
    populationMerger, ...
    primaryFlowSetter);

forceEntityToInputConnection( ...
    mdl, ...
    primaryFlowSetter, ...
    acquisitionCombiner, ...
    1);

forceEntityConnection( ...
    mdl, ...
    acquisitionCombiner, ...
    captureLoadBalancer);

fprintf('Primary -> Path Combiner path connected.\n');

% ============================================================
% 13. CREATE POST-AI FLOW ROUTER
% ============================================================

postAIRouter = ...
    [mdl '/Post AI Flow Router'];

try
    delete_block(postAIRouter);
catch
end

add_block( ...
    outputSwitchLib, ...
    postAIRouter, ...
    'Position', ...
    [1765 180 1900 310]);

set_param( ...
    postAIRouter, ...
    'NumberOutputPorts', ...
    '2');

set_param( ...
    postAIRouter, ...
    'SwitchingCriterion', ...
    'From attribute');

set_param( ...
    postAIRouter, ...
    'AttributeName', ...
    'flowType');

% ============================================================
% 14. RECAPTURE COMPLETE SINK
% ============================================================

recaptureCompleteSink = ...
    [mdl '/RECAPTURE COMPLETE'];

try
    delete_block(recaptureCompleteSink);
catch
end

add_block( ...
    sinkLib, ...
    recaptureCompleteSink, ...
    'Position', ...
    [2020 315 2180 370]);

set_param( ...
    recaptureCompleteSink, ...
    'StatNumberArrived', ...
    'on');

% ============================================================
% 15. RECAPTURE PREPARATION SERVER
% ============================================================

recaptureDelay = ...
    [mdl '/Recapture Preparation'];

try
    delete_block(recaptureDelay);
catch
end

add_block( ...
    serverLib, ...
    recaptureDelay, ...
    'Position', ...
    [1510 600 1665 650]);

set_param( ...
    recaptureDelay, ...
    'ServiceTimeFrom', ...
    'Dialog');

set_param( ...
    recaptureDelay, ...
    'ServiceTime', ...
    num2str(recapturePreparationTime,15));

% ============================================================
% 16. RECAPTURE FLOW ATTRIBUTE
% ============================================================

recaptureFlowSetter = ...
    [mdl '/Set Recapture Flow'];

try
    delete_block(recaptureFlowSetter);
catch
end

add_block( ...
    setAttributeLib, ...
    recaptureFlowSetter, ...
    'Position', ...
    [1710 600 1860 650]);

set_param( ...
    recaptureFlowSetter, ...
    'AttributeName', ...
    'flowType');

set_param( ...
    recaptureFlowSetter, ...
    'AttributeFrom', ...
    'Dialog');

set_param( ...
    recaptureFlowSetter, ...
    'AttributeValue', ...
    '2');

set_param( ...
    recaptureFlowSetter, ...
    'AttributeCreate', ...
    'on');

% ============================================================
% 17. REBUILD FULL CAPTURE PIPELINE
% ============================================================

fprintf('\nRebuilding capture pipeline...\n');

% Path Combiner -> capture load balancer

forceEntityConnection( ...
    mdl, ...
    acquisitionCombiner, ...
    captureLoadBalancer);

% Capture load balancer -> queue 1

forceEntityOutputConnection( ...
    mdl, ...
    captureLoadBalancer, ...
    captureQueue1, ...
    1);

% Capture load balancer -> queue 2

forceEntityOutputConnection( ...
    mdl, ...
    captureLoadBalancer, ...
    captureQueue2, ...
    2);

% Queue 1 -> Camera 1

forceEntityConnection( ...
    mdl, ...
    captureQueue1, ...
    captureServer1);

% Queue 2 -> Camera 2

forceEntityConnection( ...
    mdl, ...
    captureQueue2, ...
    captureServer2);

% Camera 1 -> Capture Merger IN1

forceEntityToInputConnection( ...
    mdl, ...
    captureServer1, ...
    captureMerger, ...
    1);

% Camera 2 -> Capture Merger IN2

forceEntityToInputConnection( ...
    mdl, ...
    captureServer2, ...
    captureMerger, ...
    2);

% Capture Merger -> AI queue

forceEntityConnection( ...
    mdl, ...
    captureMerger, ...
    aiQueue);

% AI queue -> TRACE AI

forceEntityConnection( ...
    mdl, ...
    aiQueue, ...
    aiServer);

% TRACE AI -> post-AI flow router

forceEntityConnection( ...
    mdl, ...
    aiServer, ...
    postAIRouter);

% flowType 1 -> TRACE Router

forceEntityOutputConnection( ...
    mdl, ...
    postAIRouter, ...
    traceRouter, ...
    1);

% flowType 2 -> recapture complete

forceEntityOutputConnection( ...
    mdl, ...
    postAIRouter, ...
    recaptureCompleteSink, ...
    2);

fprintf('Capture + AI pipeline rebuilt.\n');

% ============================================================
% 18. CREATE RECAPTURE FEEDBACK PATH
% ============================================================

fprintf('Building Route-5 feedback path...\n');

% TRACE Route 5 -> recapture preparation

forceEntityOutputConnection( ...
    mdl, ...
    traceRouter, ...
    recaptureDelay, ...
    5);

% preparation -> flowType=2

forceEntityConnection( ...
    mdl, ...
    recaptureDelay, ...
    recaptureFlowSetter);

% flowType=2 -> Path Combiner IN2

forceEntityToInputConnection( ...
    mdl, ...
    recaptureFlowSetter, ...
    acquisitionCombiner, ...
    2);

fprintf('Route-5 Path Combiner feedback connected.\n');

% ============================================================
% 19. SERVICE TIMES
% ============================================================

set_param( ...
    captureServer1, ...
    'ServiceTimeFrom', ...
    'Dialog');

set_param( ...
    captureServer1, ...
    'ServiceTime', ...
    num2str(captureTime,15));

set_param( ...
    captureServer2, ...
    'ServiceTimeFrom', ...
    'Dialog');

set_param( ...
    captureServer2, ...
    'ServiceTime', ...
    num2str(captureTime,15));

set_param( ...
    aiServer, ...
    'ServiceTimeFrom', ...
    'Dialog');

set_param( ...
    aiServer, ...
    'ServiceTime', ...
    num2str(aiTime,15));

set_param( ...
    ophServer, ...
    'ServiceTimeFrom', ...
    'Dialog');

set_param( ...
    ophServer, ...
    'ServiceTime', ...
    num2str(ophthalmologyTime,15));

set_param( ...
    humanServer, ...
    'ServiceTimeFrom', ...
    'Dialog');

set_param( ...
    humanServer, ...
    'ServiceTime', ...
    num2str(humanReviewTime,15));

% ============================================================
% 20. ROUTE LOGGERS
% ============================================================

setLoggerVariable( ...
    mdl, ...
    'Route 1 Count', ...
    'v6Route1');

setLoggerVariable( ...
    mdl, ...
    'Route 2 Count', ...
    'v6Route2');

setLoggerVariable( ...
    mdl, ...
    'Route 3 Count', ...
    'v6Route3');

setLoggerVariable( ...
    mdl, ...
    'Route 4 Count', ...
    'v6Route4');

% ============================================================
% 21. QUEUE LOGGERS
% ============================================================

setLoggerVariable( ...
    mdl, ...
    'Metric Queue 1', ...
    'v6Capture1Wait');

setLoggerVariable( ...
    mdl, ...
    'Metric Capture2 Wait', ...
    'v6Capture2Wait');

setLoggerVariable( ...
    mdl, ...
    'Metric Queue 2', ...
    'v6AIWait');

setLoggerVariable( ...
    mdl, ...
    'Metric Queue 3', ...
    'v6OphWait');

setLoggerVariable( ...
    mdl, ...
    'Metric Queue 4', ...
    'v6HumanWait');

% ============================================================
% 22. UTILIZATION LOGGERS
% ============================================================

setLoggerVariable( ...
    mdl, ...
    'Metric Util 1', ...
    'v6Capture1Util');

setLoggerVariable( ...
    mdl, ...
    'Metric Capture2 Util', ...
    'v6Capture2Util');

setLoggerVariable( ...
    mdl, ...
    'Metric Util 2', ...
    'v6AIUtil');

setLoggerVariable( ...
    mdl, ...
    'Metric Util 3', ...
    'v6OphUtil');

setLoggerVariable( ...
    mdl, ...
    'Metric Util 4', ...
    'v6HumanUtil');

% ============================================================
% 23. RECAPTURE SERVER STATISTICS
% ============================================================

set_param( ...
    recaptureDelay, ...
    'StatUtilization', ...
    'on');

set_param( ...
    recaptureDelay, ...
    'StatNumberDeparted', ...
    'off');

set_param( ...
    recaptureDelay, ...
    'StatNumberInBlock', ...
    'off');

set_param( ...
    recaptureDelay, ...
    'StatNumberPreempted', ...
    'off');

set_param( ...
    recaptureDelay, ...
    'StatPendingEntity', ...
    'off');

set_param( ...
    recaptureDelay, ...
    'StatAverageWait', ...
    'off');

set_param( ...
    recaptureDelay, ...
    'StatNumberTimedout', ...
    'off');

% ============================================================
% 24. UPDATE MODEL / GENERATE STAT PORTS
% ============================================================

set_param( ...
    mdl, ...
    'SimulationCommand', ...
    'update');

% ============================================================
% 25. RECAPTURE COMPLETE LOGGER
% ============================================================

recaptureCompleteLogger = ...
    [mdl '/Recapture Complete Count'];

try
    delete_block(recaptureCompleteLogger);
catch
end

add_block( ...
    'simulink/Sinks/To Workspace', ...
    recaptureCompleteLogger, ...
    'VariableName', ...
    'v6RecaptureComplete', ...
    'SaveFormat', ...
    'Array', ...
    'Position', ...
    [2210 315 2370 350]);

sinkPorts = get_param( ...
    recaptureCompleteSink, ...
    'PortHandles');

loggerPorts = get_param( ...
    recaptureCompleteLogger, ...
    'PortHandles');

if isempty(sinkPorts.Outport)

    error( ...
        'RECAPTURE COMPLETE statistic port unavailable.');

end

add_line( ...
    mdl, ...
    sinkPorts.Outport(1), ...
    loggerPorts.Inport(1), ...
    'autorouting', ...
    'on');

% ============================================================
% 26. RECAPTURE PREP UTILIZATION LOGGER
% ============================================================

recaptureUtilLogger = ...
    [mdl '/Metric Recapture Prep Util'];

try
    delete_block(recaptureUtilLogger);
catch
end

add_block( ...
    'simulink/Sinks/To Workspace', ...
    recaptureUtilLogger, ...
    'VariableName', ...
    'v6RecapturePrepUtil', ...
    'SaveFormat', ...
    'Array', ...
    'Position', ...
    [1700 690 1870 725]);

delayPorts = get_param( ...
    recaptureDelay, ...
    'PortHandles');

utilPorts = get_param( ...
    recaptureUtilLogger, ...
    'PortHandles');

if isempty(delayPorts.Outport)

    error( ...
        'Recapture Preparation utilization port unavailable.');

end

add_line( ...
    mdl, ...
    delayPorts.Outport(1), ...
    utilPorts.Inport(1), ...
    'autorouting', ...
    'on');

% ============================================================
% 27. VALIDATE PATH COMBINER
% ============================================================

fprintf('\n--- PATH COMBINER VALIDATION ---\n');

combinerType = get_param( ...
    acquisitionCombiner, ...
    'BlockType');

combinerInputs = get_param( ...
    acquisitionCombiner, ...
    'NumberInputPorts');

combinerPrecedence = get_param( ...
    acquisitionCombiner, ...
    'InputPortPrecedence');

fprintf( ...
    'BlockType             : %s\n', ...
    combinerType);

fprintf( ...
    'NumberInputPorts      : %s\n', ...
    combinerInputs);

fprintf( ...
    'InputPortPrecedence   : %s\n', ...
    combinerPrecedence);

if ~strcmp( ...
        combinerType, ...
        'PathCombiner')

    error( ...
        'Acquisition merge is not a Path Combiner.');

end

if ~strcmp( ...
        combinerInputs, ...
        '2')

    error( ...
        'Acquisition Path Combiner does not have 2 inputs.');

end

fprintf('Path Combiner configuration: PASS\n');

% ============================================================
% 28. VALIDATE CRITICAL CONNECTIONS
% ============================================================

fprintf('\n--- CRITICAL CONNECTION VALIDATION ---\n');

verifyEntityInputConnected( ...
    primaryFlowSetter);

verifyEntityInputConnected( ...
    acquisitionCombiner);

verifyEntityInputConnected( ...
    captureLoadBalancer);

verifyEntityInputConnected( ...
    captureQueue1);

verifyEntityInputConnected( ...
    captureQueue2);

verifyEntityInputConnected( ...
    captureServer1);

verifyEntityInputConnected( ...
    captureServer2);

verifyEntityInputConnected( ...
    captureMerger);

verifyEntityInputConnected( ...
    aiQueue);

verifyEntityInputConnected( ...
    aiServer);

verifyEntityInputConnected( ...
    postAIRouter);

verifyEntityInputConnected( ...
    traceRouter);

verifyEntityInputConnected( ...
    recaptureDelay);

verifyEntityInputConnected( ...
    recaptureFlowSetter);

verifyEntityInputConnected( ...
    recaptureCompleteSink);

fprintf('Critical V6 connections: PASS\n');

% ============================================================
% 29. ROUTER INTEGRITY
% ============================================================

if ~strcmp( ...
        get_param( ...
            postAIRouter, ...
            'SwitchingCriterion'), ...
        'From attribute')

    error( ...
        'Post-AI Flow Router criterion invalid.');

end

if ~strcmp( ...
        get_param( ...
            postAIRouter, ...
            'AttributeName'), ...
        'flowType')

    error( ...
        'Post-AI Flow Router must use flowType.');

end

if ~strcmp( ...
        get_param( ...
            traceRouter, ...
            'SwitchingCriterion'), ...
        'From attribute')

    error( ...
        'TRACE Router criterion was changed.');

end

if ~strcmp( ...
        get_param( ...
            traceRouter, ...
            'AttributeName'), ...
        'routeCode')

    error( ...
        'TRACE Router must continue using routeCode.');

end

fprintf('Router integrity: PASS\n');

% ============================================================
% 30. SOLVER
% ============================================================

set_param( ...
    mdl, ...
    'StopTime', ...
    num2str(simulationTime));

set_param( ...
    mdl, ...
    'Solver', ...
    'VariableStepDiscrete');

set_param( ...
    mdl, ...
    'MaxStep', ...
    '1');

% ============================================================
% 31. MODEL DESCRIPTION
% ============================================================

descriptionText = [ ...
    'ANEYE / NetraAI Digital Twin V6. ' ...
    'Primary and recapture acquisition traffic are merged ' ...
    'using a SimEvents Path Combiner. Route-5 cases consume ' ...
    'recapture preparation, a second fundus capture and a ' ...
    'second AI pass. Recapture cases exit after the second ' ...
    'AI pass; post-recapture clinical outcome is not inferred.'];

try

    set_param( ...
        mdl, ...
        'Description', ...
        descriptionText);

catch
end

save_system( ...
    mdl, ...
    modelFile);

fprintf('\nV6 construction: PASS\n');

% ============================================================
% 32. CLEAR LOGGING VARIABLES
% ============================================================

evalin( ...
    'base', ...
    ['clear ' ...
     'v6Route1 v6Route2 v6Route3 v6Route4 ' ...

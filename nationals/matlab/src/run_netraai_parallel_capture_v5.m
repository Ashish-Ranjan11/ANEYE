% ============================================================
% HELPER - SAFE STANDARD ENTITY CONNECTION
% ============================================================

function safeConnectEntity( ...
    model, ...
    source, ...
    destination)

src = get_param( ...
    source, ...
    'PortHandles');

dst = get_param( ...
    destination, ...
    'PortHandles');

srcPort = getEntityOutput(src,1);
dstPort = getEntityInput(dst,1);

disconnectPortLine(srcPort);
disconnectPortLine(dstPort);

add_line( ...
    model, ...
    srcPort, ...
    dstPort, ...
    'autorouting', ...
    'on');

end



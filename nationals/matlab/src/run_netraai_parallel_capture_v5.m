% ============================================================
% HELPER - ENSURE EXISTING CONNECTION
% ============================================================

function ensureEntityConnection( ...
    model, ...
    source, ...
    destination)

src = get_param( ...
    source, ...
    'PortHandles');

srcPort = ...
    getEntityOutput( ...
        src, ...
        1);

lineHandle = -1;

try
    lineHandle = get_param(srcPort,'Line');
catch
end

if isempty(lineHandle) || lineHandle == -1

    safeConnectEntity( ...
        model, ...
        source, ...
        destination);

end

end



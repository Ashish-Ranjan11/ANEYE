function results = run_netraai_resource_sweep_v7()
% RUN_NETRAAI_RESOURCE_SWEEP_V7
%
% ANEYE / NetraAI Digital Twin V7
% CORRECTED DISTRICT RESOURCE-SIZING STRESS SWEEP
%
% MATLAB / SimEvents R2014a compatible.
%
% ============================================================
% VALIDATED BASELINE
% ============================================================
%
% NetraAI_DigitalTwin_V6_RecaptureLoop
%
% ============================================================
% PURPOSE
% ============================================================
%
% Evaluate district screening capacity across:
%
%   Capture stations:
%       1
%       2
%       3
%
%   Recapture workload:
%       0%
%       5%
%       10%
%       15%
%       20%
%       25%
%       30%
%
% Total:
%
%       3 x 7 = 21 scenarios
%
% ============================================================
% PROVENANCE
% ============================================================
%
% REQUIREMENT
%   100,000 primary screenings/year
%
% MEASURED
%   AI processing = 8.67151 s
%   single frozen reference case
%
% ASSUMPTION
%   300 operating days/year
%   8 operating hours/day
%   fundus capture = 120 s
%   ophthalmology review = 30 s
%   human review = 45 s
%   recapture preparation = 20 s
%
% ENGINEERING SENSITIVITY TEST
%   recapture workload = 0% to 30%
%
% ENGINEERING GUARDRAILS
%   capture utilization < 95%
%   max capture wait < primary interarrival interval
%   downstream utilization < 95%
%   >=98% primary completion within 8-hour horizon
%
% These are NOT clinical or regulatory thresholds.
%
% ============================================================
% IMPORTANT FIXES IN THIS VERSION
% ============================================================
%
% 1. TRACE Router is explicitly preserved.
%
% 2. TRACE downstream topology is rebuilt and validated before
%    every simulation.
%
% 3. Recapture uses the validated V6 Path Combiner feedback
%    architecture.
%
% 4. Representative R30 models are saved using COPYFILE rather
%    than save_system(...,newname), avoiding R2014a open-model
%    naming conflicts.
%
% 5. Invalid zero-terminal-output simulations cause an ERROR
%    rather than entering the resource-sizing matrix.
%
% ============================================================

clc

fprintf('\n');
fprintf('============================================================\n');
fprintf(' ANEYE / NETRAAI DIGITAL TWIN V7\n');
fprintf(' CORRECTED RESOURCE-SIZING STRESS SWEEP\n');
fprintf('============================================================\n');

% ============================================================
% 1. EXECUTION MODE
% ============================================================
%
% Smoke test already passed.
%
% FALSE = full 21-scenario sweep.
% TRUE  = only 2-camera / 20%% recapture validation.
% ============================================================

SMOKE_ONLY = false;

% ============================================================
% 2. PROJECT PATHS
% ============================================================

projectRoot = pwd;

srcDir = fullfile( ...
    projectRoot, ...
    'nationals', ...
    'matlab', ...
    'src');

modelDir = fullfile( ...
    projectRoot, ...
    'nationals', ...
    'simulink');

resultsDir = fullfile( ...
    modelDir, ...
    'results');

addpath(srcDir);

if ~exist(resultsDir,'dir')
    mkdir(resultsDir);
end

baseModel = ...
    'NetraAI_DigitalTwin_V6_RecaptureLoop';

baseModelFile = fullfile( ...
    modelDir, ...
    [baseModel '.mdl']);

workingModel = ...
    'NetraAI_DigitalTwin_V7_Working';

workingModelFile = fullfile( ...
    modelDir, ...
    [workingModel '.mdl']);

if exist(baseModelFile,'file') ~= 2

    error( ...
        ['Validated V6 baseline not found: ' ...
         baseModelFile]);

end

fprintf('\nValidated V6 baseline:\n%s\n', ...
    baseModelFile);

% ============================================================
% 3. DISTRICT CONTRACT
% ============================================================

annualTarget = 100000;

workingDays = 300;

hoursPerDay = 8;

simulationHours = 8;

simulationTime = ...
    simulationHours * 3600;

operatingSecondsYear = ...
    workingDays ...
    * hoursPerDay ...
    * 3600;

arrivalPeriod = ...
    operatingSecondsYear ...
    / annualTarget;

requiredPrimaryRate = ...
    annualTarget ...
    / (workingDays * hoursPerDay);

captureTime = 120.0;
% ASSUMPTION

aiTime = 8.67151;
% MEASURED - SINGLE FROZEN REFERENCE CASE

ophthalmologyTime = 30.0;
% ASSUMPTION

humanReviewTime = 45.0;
% ASSUMPTION

recapturePreparationTime = 20.0;
% ASSUMPTION

captureCapacityPerStation = ...
    3600 / captureTime;

% ============================================================
% 4. SWEEP DEFINITION
% ============================================================

if SMOKE_ONLY

    cameraCounts = ...
        [2];

    recapturePercentages = ...
        [20];

    fprintf('\n');
    fprintf('*** SMOKE TEST MODE ENABLED ***\n');

else

    cameraCounts = ...
        [1 2 3];

    recapturePercentages = ...
        [0 5 10 15 20 25 30];

    fprintf('\n');
    fprintf('*** FULL 21-SCENARIO SWEEP ENABLED ***\n');

end

numCameraScenarios = ...
    length(cameraCounts);

numRecaptureScenarios = ...
    length(recapturePercentages);

numScenarios = ...
    numCameraScenarios ...
    * numRecaptureScenarios;

% ============================================================
% 5. PRINT SCENARIO CONTRACT
% ============================================================

fprintf('\n--- V7 SCENARIO CONTRACT ---\n');

fprintf( ...
    'Annual requirement        : %.0f/year\n', ...
    annualTarget);

fprintf( ...
    'Required primary rate     : %.4f cases/hour\n', ...
    requiredPrimaryRate);

fprintf( ...
    'Primary arrival interval  : %.3f s\n', ...
    arrivalPeriod);

fprintf( ...
    'Capture service           : %.2f s [ASSUMPTION]\n', ...
    captureTime);

fprintf( ...
    'Per-camera capacity       : %.2f capture events/hour\n', ...
    captureCapacityPerStation);

fprintf( ...
    'AI service                : %.5f s [MEASURED-1 CASE]\n', ...
    aiTime);

fprintf( ...
    'Recapture preparation     : %.2f s [ASSUMPTION]\n', ...
    recapturePreparationTime);

fprintf( ...
    'Simulation horizon        : %.0f h/scenario\n', ...
    simulationHours);

fprintf( ...
    'Number of scenarios       : %d\n', ...
    numScenarios);

% ============================================================
% 6. RESULT MATRIX
% ============================================================
%
% Columns:
%
%  1 Cameras
%  2 RecapturePct
%  3 TheoreticalCaptureUtil
%  4 PrimaryGenerated
%  5 PrimaryCompleted
%  6 PrimaryIncomplete
%  7 CompletionFraction
%  8 RecaptureCompleted
%  9 ObservedRecapturePct
% 10 Capture1Util
% 11 Capture2Util
% 12 Capture3Util
% 13 MaxCaptureUtil
% 14 Capture1WaitSec
% 15 Capture2WaitSec
% 16 Capture3WaitSec
% 17 MaxCaptureWaitSec
% 18 AIUtil
% 19 OphUtil
% 20 HumanUtil
% 21 PrimaryRatePerHour
% 22 AnnualizedPrimaryEq
% 23 Stable
% ============================================================

M = zeros(numScenarios,23);

scenarioIndex = 0;

% ============================================================
% 7. LOAD SIMEVENTS LIBRARY
% ============================================================

load_system('simeventslib');

% ============================================================
% 8. BEGIN FULL SWEEP
% ============================================================

for cameraIndex = 1:numCameraScenarios

    cameraCount = ...
        cameraCounts(cameraIndex);

    for recaptureIndex = 1:numRecaptureScenarios

        recapturePercent = ...
            recapturePercentages(recaptureIndex);

        recaptureFraction = ...
            recapturePercent / 100;

        scenarioIndex = ...
            scenarioIndex + 1;

        fprintf('\n');
        fprintf('------------------------------------------------------------\n');

        fprintf( ...
            ' V7 SCENARIO %02d/%02d : %d CAMERA(S), %d%% RECAPTURE\n', ...
            scenarioIndex, ...
            numScenarios, ...
            cameraCount, ...
            recapturePercent);

        fprintf('------------------------------------------------------------\n');

        % ====================================================
        % 8A. CLOSE POSSIBLE LEFTOVER WORKING MODEL
        % ====================================================

        try
            close_system(workingModel,0);
        catch
        end

        % ====================================================
        % 8B. DELETE OLD WORKING FILE
        % ====================================================

        if exist(workingModelFile,'file') == 2

            try
                delete(workingModelFile);
            catch
            end

        end

        % ====================================================
        % 8C. CLONE VALIDATED V6
        % ====================================================

        load_system(baseModelFile);

        save_system( ...
            baseModel, ...
            workingModelFile);

        try
            close_system(baseModel,0);
        catch
        end

        load_system(workingModelFile);

        mdl = workingModel;

        fprintf('Fresh V7 model cloned from validated V6.\n');

        % ====================================================
        % 8D. VERIFY TRACE ROUTER BEFORE MODIFICATION
        % ====================================================

        traceRouter = ...
            [mdl '/TRACE Router'];

        verifyBlockExists( ...
            traceRouter, ...
            'TRACE Router missing before V7 construction.');

        fprintf('TRACE Router before population rebuild: PASS\n');

        % ====================================================
        % 8E. CREATE DETERMINISTIC ROUTE SEQUENCE
        % ====================================================

        recaptureSlots = ...
            round(recapturePercent / 5);

        routeSequence = ...
            buildRouteSequence20( ...
                recaptureSlots);

        fprintf('Primary route sequence: ');

        for q = 1:length(routeSequence)

            fprintf( ...
                '%d ', ...
                routeSequence(q));

        end

        fprintf('\n');

        % ====================================================
        % 8F. REBUILD PRIMARY POPULATION
        % ====================================================

        configureRoutePopulation( ...
            mdl, ...
            routeSequence);

        % ====================================================
        % 8G. REPAIR TRACE PIPELINE
        % ====================================================

        repairTracePipeline(mdl);

        verifyCriticalFlow(mdl);

        removeDanglingLines(mdl);

        % ====================================================
        % 8H. CONFIGURE NUMBER OF CAMERAS
        % ====================================================

        configureCaptureResources( ...
            mdl, ...
            cameraCount, ...
            captureTime);

        % ====================================================
        % 8I. REPAIR AGAIN AFTER CAMERA MODIFICATION
        % ====================================================

        repairTracePipeline(mdl);

        verifyCriticalFlow(mdl);

        removeDanglingLines(mdl);

        % ====================================================
        % 8J. REASSERT SERVICE TIMES
        % ====================================================

        set_param( ...
            [mdl '/TRACE AI Processing'], ...
            'ServiceTimeFrom', ...
            'Dialog');

        set_param( ...
            [mdl '/TRACE AI Processing'], ...
            'ServiceTime', ...
            num2str(aiTime,15));

        set_param( ...
            [mdl '/Ophthalmologist Review'], ...
            'ServiceTimeFrom', ...
            'Dialog');

        set_param( ...
            [mdl '/Ophthalmologist Review'], ...
            'ServiceTime', ...
            num2str(ophthalmologyTime,15));

        set_param( ...
            [mdl '/Human Reviewer'], ...
            'ServiceTimeFrom', ...
            'Dialog');

        set_param( ...
            [mdl '/Human Reviewer'], ...
            'ServiceTime', ...
            num2str(humanReviewTime,15));

        set_param( ...
            [mdl '/Recapture Preparation'], ...
            'ServiceTimeFrom', ...
            'Dialog');

        set_param( ...
            [mdl '/Recapture Preparation'], ...
            'ServiceTime', ...
            num2str(recapturePreparationTime,15));

        % ====================================================
        % 8K. CONFIGURE LOGGERS
        % ====================================================

        configureV7Loggers( ...
            mdl, ...
            cameraCount);

        % ====================================================
        % 8L. SIMULATION SETTINGS
        % ====================================================

        set_param( ...
            mdl, ...
            'StopTime', ...
            num2str(simulationTime));

        set_param( ...
            mdl, ...
            'Solver', ...
            'VariableStepDiscrete');

        set_param( ...
            mdl, ...
            'MaxStep', ...
            '1');

        % ====================================================
        % 8M. FINAL PRE-SIM REPAIR
        % ====================================================

        repairTracePipeline(mdl);

        removeDanglingLines(mdl);

        verifyCriticalFlow(mdl);

        set_param( ...
            mdl, ...
            'SimulationCommand', ...
            'update');

        % ====================================================
        % 8N. FINAL TRACE ROUTER INTEGRITY CHECK
        % ====================================================

        verifyBlockExists( ...
            [mdl '/TRACE Router'], ...
            'TRACE Router disappeared before simulation.');

        traceCriterion = get_param( ...
            [mdl '/TRACE Router'], ...
            'SwitchingCriterion');

        traceAttribute = get_param( ...
            [mdl '/TRACE Router'], ...
            'AttributeName');

        if ~strcmp( ...
                traceCriterion, ...
                'From attribute')

            error( ...
                'TRACE Router switching criterion corrupted.');

        end

        if ~strcmp( ...
                traceAttribute, ...
                'routeCode')

            error( ...
                'TRACE Router no longer uses routeCode.');

        end

        fprintf('TRACE Router final integrity: PASS\n');

        % ====================================================
        % 8O. SAVE WORKING MODEL
        % ====================================================

        save_system( ...
            mdl, ...
            workingModelFile);

        % ====================================================
        % 8P. CLEAR OUTPUT VARIABLES
        % ====================================================

        evalin( ...
            'base', ...
            ['clear ' ...
             'v7Route1 v7Route2 v7Route3 v7Route4 ' ...
             'v7RecaptureComplete ' ...
             'v7Cap1Wait v7Cap2Wait v7Cap3Wait ' ...
             'v7Cap1Util v7Cap2Util v7Cap3Util ' ...
             'v7AIWait v7OphWait v7HumanWait ' ...
             'v7AIUtil v7OphUtil v7HumanUtil']);

        % ====================================================
        % 8Q. RUN SIMULATION
        % ====================================================

        fprintf('\nRunning simulation...\n');

        simCommand = ...
            ['sim(''' mdl ''');'];

        evalin( ...
            'base', ...
            simCommand);

        fprintf('Simulation complete.\n');

        % ====================================================
        % 8R. READ TRACE ROUTE COUNTS
        % ====================================================

        routeCounts = ...
            zeros(1,4);

        for r = 1:4

            variableName = ...
                ['v7Route' num2str(r)];

            assertBaseVariable( ...
                variableName);

            routeCounts(r) = ...
                getLastMetric( ...
                    evalin( ...
                        'base', ...
                        variableName));

        end

        assertBaseVariable( ...
            'v7RecaptureComplete');

        recaptureComplete = ...
            getLastMetric( ...
                evalin( ...
                    'base', ...
                    'v7RecaptureComplete'));

        % ====================================================
        % 8S. READ CAMERA METRICS
        % ====================================================

        captureUtil = ...
            zeros(1,3);

        captureWait = ...
            zeros(1,3);

        for c = 1:cameraCount

            waitVariable = ...
                ['v7Cap' num2str(c) 'Wait'];

            utilVariable = ...
                ['v7Cap' num2str(c) 'Util'];

            assertBaseVariable( ...
                waitVariable);

            assertBaseVariable( ...
                utilVariable);

            captureWait(c) = ...
                getLastMetric( ...
                    evalin( ...
                        'base', ...
                        waitVariable));

            captureUtil(c) = ...
                getLastMetric( ...
                    evalin( ...
                        'base', ...
                        utilVariable));

        end

        % ====================================================
        % 8T. READ DOWNSTREAM METRICS
        % ====================================================

        assertBaseVariable( ...
            'v7AIUtil');

        assertBaseVariable( ...
            'v7OphUtil');

        assertBaseVariable( ...
            'v7HumanUtil');

        aiUtil = ...
            getLastMetric( ...
                evalin( ...
                    'base', ...
                    'v7AIUtil'));

        ophUtil = ...
            getLastMetric( ...
                evalin( ...
                    'base', ...
                    'v7OphUtil'));

        humanUtil = ...
            getLastMetric( ...
                evalin( ...
                    'base', ...
                    'v7HumanUtil'));

        % ====================================================
        % 8U. DERIVED METRICS
        % ====================================================

        expectedPrimary = ...
            floor( ...
                simulationTime ...
                / arrivalPeriod) ...
            + 1;

        primaryCompleted = ...
            sum(routeCounts) ...
            + recaptureComplete;

        primaryIncomplete = ...
            max( ...
                0, ...
                expectedPrimary ...
                - primaryCompleted);

        completionFraction = ...
            primaryCompleted ...
            / max(1,expectedPrimary);

        observedRecaptureFraction = ...
            recaptureComplete ...
            / max(1,primaryCompleted);

        observedPrimaryRate = ...
            primaryCompleted ...
            / simulationHours;

        annualizedPrimaryEquivalent = ...
            observedPrimaryRate ...
            * hoursPerDay ...
            * workingDays;

        maxCaptureUtil = ...
            max( ...
                captureUtil(1:cameraCount));

        maxCaptureWait = ...
            max( ...
                captureWait(1:cameraCount));

        maxDownstreamUtil = ...
            max( ...
                [aiUtil ...
                 ophUtil ...
                 humanUtil]);

        % ====================================================
        % 8V. THEORETICAL CAPTURE UTILIZATION
        % ====================================================

        theoreticalCaptureDemand = ...
            requiredPrimaryRate ...
            * (1 + recaptureFraction);

        totalNominalCaptureCapacity = ...
            cameraCount ...
            * captureCapacityPerStation;

        theoreticalAggregateCaptureUtil = ...
            theoreticalCaptureDemand ...
            / totalNominalCaptureCapacity;

        % ====================================================
        % 8W. FLOW-INTEGRITY CHECKS
        % ====================================================

        if primaryCompleted <= 0

            error( ...
                ['V7 FLOW INTEGRITY FAILURE: ' ...
                 'zero primary cases reached terminal outcomes.']);

        end

        % ----------------------------------------------------
        % Only enforce recapture completion if system is not
        % so overloaded that feedback entities cannot complete.
        %
        % For stable 2/3-camera scenarios, a nonzero requested
        % recapture fraction MUST produce recapture completions.
        % ----------------------------------------------------

        if recapturePercent > 0 && ...
                theoreticalAggregateCaptureUtil < 0.95 && ...
                recaptureComplete <= 0

            error( ...
                ['V7 RECAPTURE INTEGRITY FAILURE: ' ...
                 'requested recapture workload but zero ' ...
                 'recapture passes completed.']);

        end

        % ====================================================
        % 8X. ENGINEERING STABILITY RULE
        % ====================================================

        captureStable = ...
            maxCaptureUtil < 0.95;

        queueStable = ...
            maxCaptureWait < arrivalPeriod;

        downstreamStable = ...
            maxDownstreamUtil < 0.95;

        completionStable = ...
            completionFraction >= 0.98;

        stable = ...
            captureStable ...
            && queueStable ...
            && downstreamStable ...
            && completionStable;

        % ====================================================
        % 8Y. STORE RESULT
        % ====================================================

        M(scenarioIndex,:) = [ ...
            cameraCount, ...
            recapturePercent, ...
            theoreticalAggregateCaptureUtil, ...
            expectedPrimary, ...
            primaryCompleted, ...
            primaryIncomplete, ...
            completionFraction, ...
            recaptureComplete, ...
            observedRecaptureFraction*100, ...
            captureUtil(1), ...
            captureUtil(2), ...
            captureUtil(3), ...
            maxCaptureUtil, ...
            captureWait(1), ...
            captureWait(2), ...
            captureWait(3), ...
            maxCaptureWait, ...
            aiUtil, ...
            ophUtil, ...
            humanUtil, ...
            observedPrimaryRate, ...
            annualizedPrimaryEquivalent, ...
            double(stable)];

        % ====================================================
        % 8Z. PRINT SCENARIO RESULT
        % ====================================================

        fprintf('\n');
        fprintf('--- SCENARIO RESULT ---\n');

        fprintf( ...
            'Theoretical capture util : %.4f\n', ...
            theoreticalAggregateCaptureUtil);

        fprintf( ...
            'Simulated max cap util   : %.4f\n', ...
            maxCaptureUtil);

        fprintf( ...
            'Max capture wait         : %.3f s\n', ...
            maxCaptureWait);

        fprintf( ...
            'TRACE AI util            : %.4f\n', ...
            aiUtil);

        fprintf( ...
            'Ophthalmologist util     : %.4f\n', ...
            ophUtil);

        fprintf( ...
            'Human reviewer util      : %.4f\n', ...
            humanUtil);

        fprintf( ...
            'Primary complete         : %.0f / %.0f\n', ...
            primaryCompleted, ...
            expectedPrimary);

        fprintf( ...
            'Observed recapture       : %.2f %%\n', ...
            observedRecaptureFraction*100);

        fprintf( ...
            'Annualized primary eq.   : %.0f/year\n', ...
            annualizedPrimaryEquivalent);

        if stable

            fprintf( ...
                'STATUS                   : STABLE\n');

        else

            fprintf( ...
                'STATUS                   : CAPACITY PRESSURE\n');

        end

        % ====================================================
        % 8AA. SMOKE PARITY CHECK
        % ====================================================

        if SMOKE_ONLY

            fprintf('\n');
            fprintf('--- V6 PARITY SMOKE CHECK ---\n');

            smokeCompletionOK = ...
                completionFraction >= 0.98;

            smokeRecaptureOK = ...
                observedRecaptureFraction >= 0.17 ...
                && observedRecaptureFraction <= 0.23;

            smokeCaptureUtilOK = ...
                maxCaptureUtil >= 0.75 ...
                && maxCaptureUtil <= 0.90;

            smokeAIUtilOK = ...
                aiUtil >= 0.105 ...
                && aiUtil <= 0.15;

            fprintf( ...
                'Completion parity        : %d\n', ...
                smokeCompletionOK);

            fprintf( ...
                'Recapture parity         : %d\n', ...
                smokeRecaptureOK);

            fprintf( ...
                'Capture-util parity      : %d\n', ...
                smokeCaptureUtilOK);

            fprintf( ...
                'AI-util parity           : %d\n', ...
                smokeAIUtilOK);

            if ~( ...
                    smokeCompletionOK ...
                    && smokeRecaptureOK ...
                    && smokeCaptureUtilOK ...
                    && smokeAIUtilOK)

                error( ...
                    'V7 SMOKE TEST FAILED.');

            end

            fprintf('V7 SMOKE TEST: PASS\n');

        end

        % ====================================================
        % 8AB. SAVE REPRESENTATIVE 30%% MODEL
        % ====================================================
        %
        % IMPORTANT R2014a FIX:
        %
        % Do NOT:
        %
        %   save_system(mdl, representativeFile)
        %
        % That can cause the current model to become loaded under
        % the representative model name and later produce:
        %
        %   "model of same name is currently open"
        %
        % Instead:
        %
        %   save working model
        %   close any old representative model
        %   delete old representative file
        %   COPY working .mdl file
        % ====================================================

        if ~SMOKE_ONLY && ...
                recapturePercent == 30

            representativeModelName = sprintf( ...
                'NetraAI_DigitalTwin_V7_C%d_R30', ...
                cameraCount);

            representativeName = ...
                [representativeModelName '.mdl'];

            representativeFile = fullfile( ...
                modelDir, ...
                representativeName);

            % ------------------------------------------------
            % Save current working model first.
            % ------------------------------------------------

            save_system( ...
                mdl, ...
                workingModelFile);

            % ------------------------------------------------
            % Close old representative model if loaded.
            % ------------------------------------------------

            try

                close_system( ...
                    representativeModelName, ...
                    0);

            catch
            end

            % ------------------------------------------------
            % Delete old representative file.
            % ------------------------------------------------

            if exist( ...
                    representativeFile, ...
                    'file') == 2

                try
                    delete(representativeFile);
                catch
                end

            end

            % ------------------------------------------------
            % Copy working model file.
            % ------------------------------------------------

            [copyStatus,copyMessage] = copyfile( ...
                workingModelFile, ...
                representativeFile);

            if copyStatus ~= 1

                error( ...
                    ['Unable to save representative model: ' ...
                     copyMessage]);

            end

            fprintf( ...
                'Saved representative copy: %s\n', ...
                representativeName);

        end

        % ====================================================
        % 8AC. CLOSE SCENARIO
        % ====================================================

        try
            close_system(mdl,0);
        catch
        end

    end

end

% ============================================================
% 9. RESULT STRUCT
% ============================================================

results.version = ...
    'NETRAAI_V7_RESOURCE_SWEEP_FINAL_V3';

results.smokeOnly = ...
    SMOKE_ONLY;

results.provenance.annualTarget = ...
    'REQUIREMENT';

results.provenance.captureTime = ...
    'ASSUMPTION';

results.provenance.aiTime = ...
    'MEASURED_SINGLE_REFERENCE_CASE';

results.provenance.recapturePercentages = ...
    'ENGINEERING_SENSITIVITY_TEST';

results.provenance.routeDistribution = ...
    'DETERMINISTIC_ENGINEERING_TEST';

results.provenance.stabilityThresholds = ...
    'ENGINEERING_GUARDRAILS';

results.cameraCounts = ...
    cameraCounts;

results.recapturePercentages = ...
    recapturePercentages;

results.matrix = ...
    M;

results.columns = { ...
    'Cameras', ...
    'RecapturePct', ...
    'TheoreticalCaptureUtil', ...
    'PrimaryGenerated', ...
    'PrimaryCompleted', ...
    'PrimaryIncomplete', ...
    'CompletionFraction', ...
    'RecaptureCompleted', ...
    'ObservedRecapturePct', ...
    'Capture1Util', ...
    'Capture2Util', ...
    'Capture3Util', ...
    'MaxCaptureUtil', ...
    'Capture1WaitSec', ...
    'Capture2WaitSec', ...
    'Capture3WaitSec', ...
    'MaxCaptureWaitSec', ...
    'AIUtil', ...
    'OphUtil', ...
    'HumanUtil', ...
    'PrimaryRatePerHour', ...
    'AnnualizedPrimaryEq', ...
    'Stable'};

% ============================================================
% 10. PRINT RESOURCE-SIZING MATRIX
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf(' NETRAAI V7 RESOURCE-SIZING MATRIX\n');
fprintf('============================================================\n');

fprintf('\n');

fprintf( ...
    '%5s %7s %10s %10s %10s %11s %10s %10s\n', ...
    'Cams', ...
    'Recap%', ...
    'TheoryUtil', ...

% ============================================================
% DISCONNECT LINE FROM PORT
% ============================================================

function disconnectPortLine( ...
    portHandle)

if isempty(portHandle)
    return;
end

try

    lineHandle = get_param( ...
        portHandle, ...
        'Line');

    if ~isempty(lineHandle) && ...
            lineHandle ~= -1

        delete_line( ...
            lineHandle);

    end

catch
end

end


% ============================================================
% GET ENTITY OUTPUT PORT
% ============================================================

function h = getEntityOutput( ...
    portHandles, ...
    index)

if isfield( ...
        portHandles, ...
        'RConn') && ...
        length(portHandles.RConn) >= index

    h = ...
        portHandles.RConn(index);

    return;

end

if isfield( ...
        portHandles, ...
        'Outport') && ...
        length(portHandles.Outport) >= index

    h = ...
        portHandles.Outport(index);

    return;

end

error( ...
    ['Unable to resolve entity output port ' ...
     num2str(index)]);

end



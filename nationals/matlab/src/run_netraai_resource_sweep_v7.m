% ============================================================
% BUILD 20-POSITION TRACE ROUTE SEQUENCE
% ============================================================

function sequence = buildRouteSequence20( ...
    recaptureSlots)

if recaptureSlots < 0 || ...
        recaptureSlots > 20

    error( ...
        'recaptureSlots must be between 0 and 20.');

end

sequence = ...
    zeros(1,20);

recapturePositions = [];

% ------------------------------------------------------------
% Spread recapture slots approximately evenly.
% ------------------------------------------------------------

if recaptureSlots > 0

    for k = 1:recaptureSlots

        pos = round( ...
            ((k - 0.5) * 20) ...
            / recaptureSlots);

        pos = max( ...
            1, ...
            min(20,pos));

        while any( ...
                recapturePositions == pos)

            pos = ...
                pos + 1;

            if pos > 20
                pos = 1;
            end

        end

        recapturePositions(end+1) = ...
            pos;

    end

end

% ------------------------------------------------------------
% Remaining slots cycle through TRACE routes 1-4.
% ------------------------------------------------------------

normalIndex = 1;

for i = 1:20

    if any( ...
            recapturePositions == i)

        sequence(i) = 5;

    else

        sequence(i) = ...
            mod( ...
                normalIndex - 1, ...
                4) ...
            + 1;

        normalIndex = ...
            normalIndex + 1;

    end

end

end



% ============================================================
% REMOVE DANGLING GRAPHICAL LINES
% ============================================================

function removeDanglingLines(mdl)

lines = find_system( ...
    mdl, ...
    'FindAll', ...
    'on', ...
    'Type', ...
    'line');

removed = 0;

for k = 1:length(lines)

    try

        src = get_param( ...
            lines(k), ...
            'SrcPortHandle');

        dst = get_param( ...
            lines(k), ...
            'DstPortHandle');

        badSource = ...
            isempty(src) || ...
            all(src == -1);

        badDestination = ...
            isempty(dst) || ...
            all(dst == -1);

        if badSource || ...
                badDestination

            delete_line( ...
                lines(k));

            removed = ...
                removed + 1;

        end

    catch
    end

end

fprintf( ...
    'Dangling graphical lines removed: %d\n', ...
    removed);

end


